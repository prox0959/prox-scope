def scan(target: str, session: requests.Session) -> list:
    """Identify front-facing WAF and reverse-proxy protections."""
    findings = []
    detected_wafs = []

    try:
        resp = session.get(target, timeout=session.timeout, allow_redirects=True)
    except requests.RequestException:
        return findings

    headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}
    server = headers_lower.get("server", "")
    cookies = [c.name.lower() for c in resp.cookies]
    body_lower = resp.text.lower()

    for waf in WAF_SIGNATURES:
        detected = False
        reason = ""

        for h in waf.get("headers", []):
            if h.lower() in headers_lower:
                detected = True
                reason = f"Header: {h}"
                break

        if not detected and "server" in waf:
            for s in waf["server"]:
                if s.lower() in server:
                    detected = True
                    reason = f"Server: {server}"
                    break

        if not detected and "cookies" in waf:
            for c_name in waf["cookies"]:
                if any(c_name.lower() in c for c in cookies):
                    detected = True
                    reason = f"Cookie: {c_name}"
                    break

        if not detected and "body" in waf:
            for b in waf["body"]:
                if b.lower() in body_lower:
                    detected = True
                    reason = f"Body: {b}"
                    break

        if detected and waf["name"] not in detected_wafs:
            detected_wafs.append(waf["name"])
            findings.append(Finding(
                module="WAF Detection",
                severity=INFO,
                title=f"WAF/CDN Protection Active: {waf['name']}",
                description=f"Front-facing {waf['name']} Web Application Firewall detected. Probing requests may be filtered or throttled.",
                evidence=reason,
            ))

    return findings
